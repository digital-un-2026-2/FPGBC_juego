static const uint16_t pow10[5] = { 10000U, 1000U, 100U, 10U, 1U };

void gfx_init(void)
{
    set_bkg_palette(0, 8, bg_palettes);
    set_sprite_palette(0, 6, spr_palettes);
    set_bkg_data(0, BG_TILE_COUNT, bg_tiles);
    set_sprite_data(0, SPR_TILE_COUNT, spr_tiles);
}

void gfx_set_tile(uint8_t tx, uint8_t ty, uint8_t tile, uint8_t pal)
{
    set_bkg_tile_xy(tx, ty, tile);
    VBK_REG = 1;
    set_bkg_tile_xy(tx, ty, pal);
    VBK_REG = 0;
}

void gfx_clear_screen(uint8_t tile, uint8_t pal)
{
    fill_bkg_rect(0, 0, 20, 18, tile);
    VBK_REG = 1;
    fill_bkg_rect(0, 0, 20, 18, pal);
    VBK_REG = 0;
}

uint8_t gfx_star_tile(uint8_t tx, uint8_t ty)
{
    uint8_t h = (uint8_t)((tx * 3U + ty * 5U) & 7U);
    if (h == 1U) return TILE_STAR1;
    if (h == 5U) return TILE_STAR2;
    return TILE_EMPTY;
}

void gfx_draw_starfield(uint8_t start_ty, uint8_t end_ty)
{
    uint8_t x, y;
    uint8_t rows = (uint8_t)(end_ty - start_ty + 1U);
    fill_bkg_rect(0U, start_ty, 20U, rows, TILE_EMPTY);
    VBK_REG = 1;
    fill_bkg_rect(0U, start_ty, 20U, rows, PAL_BG_UI);
    VBK_REG = 0;

    for (y = start_ty; y <= end_ty; y++) {
        for (x = 0U; x < 20U; x++) {
            uint8_t t = gfx_star_tile(x, y);
            if (t != TILE_EMPTY) {
                gfx_set_tile(x, y, t, PAL_BG_UI);
            }
        }
    }
}

static uint8_t char_to_tile(char c)
{
    if (c >= 'A' && c <= 'Z') return (uint8_t)(TILE_LETTER_A + (c - 'A'));
    if (c >= 'a' && c <= 'z') return (uint8_t)(TILE_LETTER_A + (c - 'a'));
    if (c >= '0' && c <= '9') return (uint8_t)(TILE_DIGIT0 + (c - '0'));
    if (c == ':') return TILE_COLON;
    if (c == '!') return TILE_EXCL;
    if (c == '-') return TILE_DASH;
    if (c == '=') return TILE_EQ;
    if (c == '/') return TILE_SLASH;
    if (c == '>') return TILE_CURSOR;
    return TILE_EMPTY;
}

void gfx_draw_text(uint8_t tx, uint8_t ty, const char *str, uint8_t pal)
{
    while (*str && tx < 20U) {
        gfx_set_tile(tx, ty, char_to_tile(*str), pal);
        tx++;
        str++;
    }
}

void gfx_draw_number(uint8_t tx, uint8_t ty, uint16_t val, uint8_t digits, uint8_t pal)
{
    uint8_t i;
    uint8_t start = (digits >= 5U) ? 0U : (uint8_t)(5U - digits);

    for (i = start; i < 5U && tx < 20U; i++) {
        uint16_t p = pow10[i];
        uint8_t d = 0U;
        while (val >= p && d < 9U) {
            val -= p;
            d++;
        }
        gfx_set_tile(tx++, ty, (uint8_t)(TILE_DIGIT0 + d), pal);
    }
}
